"""Presentation-only corrections of known imported spelling; stored text stays intact."""
def readable_rules(text):
    replacements={
        'Кул даун':'Перезарядка', 'Кулдаун':'Перезарядка', 'контр атака':'контратака',
        'Крит неудачу':'критическую неудачу', 'дэбафф':'отрицательный эффект',
        'стак до 5':'до 5 наложений', '3х':'3 срабатывания', 'Тикающий':'Периодический',
        'Видящий - возможность видеть суть вещей (трансформируемый)':'Видящий — позволяет видеть суть вещей (трансформируемая способность).',
        'Скорострел - возможность нанести две атаки одновременно (рукопашка трансформируемый)':'Скорострел — позволяет провести две атаки одновременно (рукопашная, трансформируемая способность).',
        'Совершенная контратака - всякий раз контратакую атаку ближнего боя ':'Совершенная контратака — позволяет ответить на каждую атаку ближнего боя.',
        'Десница Ока - раз в три хода пробитие +10 +урон 1к6 игнорирует критическую неудачу (Перезарядка 7 дней)':'Десница Ока — пробитие +10, дополнительный урон 1d6; игнорирует критическую неудачу. В исходном листе указаны и «раз в три хода», и «перезарядка 7 дней» — это правило нужно уточнить.',
    }
    for original,corrected in replacements.items():text=text.replace(original,corrected)
    return text
